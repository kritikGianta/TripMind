"""Builds ops/grafana/dashboards/tripmind-overview.json.

Dashboards are code: edit the panel list here, run `python ops/grafana/build_dashboard.py`, and
commit both files. Grafana loads the JSON at start-up (provisioning) and forbids UI edits, so
the repository is the source of truth.
"""

from __future__ import annotations

import json
from pathlib import Path

DS = {"type": "prometheus", "uid": "prometheus"}
OUT = Path(__file__).parent / "dashboards" / "tripmind-overview.json"


def row(title: str, y: int) -> dict[str, object]:
    return {"type": "row", "title": title, "collapsed": False,
            "gridPos": {"h": 1, "w": 24, "x": 0, "y": y}, "panels": []}


def panel(kind: str, title: str, targets: list[tuple[str, str]], x: int, y: int, w: int = 8,
          h: int = 8, unit: str = "short", description: str = "") -> dict[str, object]:
    return {
        "type": kind,
        "title": title,
        "description": description,
        "datasource": DS,
        "gridPos": {"h": h, "w": w, "x": x, "y": y},
        "fieldConfig": {"defaults": {"unit": unit}, "overrides": []},
        "options": {"legend": {"displayMode": "list", "placement": "bottom"},
                    "reduceOptions": {"calcs": ["lastNotNull"]}},
        "targets": [{"datasource": DS, "expr": expr, "legendFormat": legend, "refId": chr(65 + i)}
                    for i, (expr, legend) in enumerate(targets)],
    }


def build() -> dict[str, object]:
    panels: list[dict[str, object]] = []
    y = 0
    panels.append(row("Traffic and health", y)); y += 1
    panels += [
        panel("timeseries", "Requests per second",
              [("sum(rate(http_requests_total[1m]))", "all"),
               ('sum(rate(http_requests_total{status=~"5.."}[1m]))', "5xx")], 0, y, unit="reqps"),
        panel("timeseries", "Latency p95 by route",
              [("histogram_quantile(0.95, sum by (le, route) "
                "(rate(http_request_duration_seconds_bucket[5m])))", "{{route}}")],
              8, y, unit="s"),
        panel("stat", "Server error rate (5m)",
              [('100 * sum(rate(http_requests_total{status=~"5.."}[5m])) / '
                "clamp_min(sum(rate(http_requests_total[5m])), 1e-9)", "")], 16, y, unit="percent",
              description="Share of requests answered with 5xx."),
    ]
    y += 8
    panels.append(row("Search", y)); y += 1
    panels += [
        panel("timeseries", "Searches per minute",
              [("60 * sum by (vertical, result) (rate(searches_total[5m]))",
                "{{vertical}} {{result}}")], 0, y),
        panel("stat", "Empty searches (15m)",
              [('100 * sum(rate(searches_total{result="empty"}[15m])) / '
                "clamp_min(sum(rate(searches_total[15m])), 1e-9)", "")], 8, y, unit="percent",
              description="Searches that found nothing. High values usually mean dates outside "
              "the dataset's travel window."),
        panel("timeseries", "Search latency p95",
              [("histogram_quantile(0.95, sum by (le, vertical) "
                "(rate(search_duration_seconds_bucket[5m])))", "{{vertical}}")], 16, y, unit="s"),
    ]
    y += 8
    panels.append(row("Bookings", y)); y += 1
    panels += [
        panel("bargauge", "Checkout holds by outcome",
              [("sum by (outcome) (increase(booking_holds_total[$__range]))", "{{outcome}}")],
              0, y, description="sold_out = someone else took the last seat or room first; "
              "price_changed = the server re-priced before holding."),
        panel("bargauge", "Payments by outcome",
              [("sum by (outcome) (increase(payments_total[$__range]))", "{{outcome}}")], 8, y),
        panel("stat", "Confirmed booking value (INR)",
              [('sum(increase(booking_revenue_minor_total{currency="INR"}[$__range])) / 100', "")],
              16, y, unit="currencyINR",
              description="Simulated payments; demo data, not real revenue."),
    ]
    y += 8
    panels += [
        panel("timeseries", "Holds expired and refunds",
              [("sum(increase(holds_expired_total[5m]))", "holds expired"),
               ("sum by (reason) (increase(refunds_minor_total[5m])) / 100", "refunded ({{reason}})")],
              0, y),
        panel("bargauge", "Plans generated by priority",
              [("sum by (priority) (increase(trip_plans_total[$__range]))", "{{priority}}")], 8, y),
        panel("bargauge", "Disruptions and recovery choices",
              [("sum by (kind) (increase(disruptions_total[$__range]))", "{{kind}}"),
               ("sum by (resolution) (increase(recovery_resolutions_total[$__range]))",
                "recovered: {{resolution}}")], 16, y),
    ]
    y += 8
    panels.append(row("Data and security", y)); y += 1
    panels += [
        panel("bargauge", "Imported rows by entity",
              [("sum by (entity, outcome) (increase(import_rows_total[$__range]))",
                "{{entity}} {{outcome}}")], 0, y, w=12),
        panel("timeseries", "Sign-in events",
              [("sum by (event, outcome) (rate(auth_events_total[5m])) * 60",
                "{{event}} {{outcome}}")], 12, y, w=12,
              description="Per minute. A spike in login failures suggests password guessing."),
    ]
    return {
        "uid": "tripmind-overview",
        "title": "TripMind overview",
        "tags": ["tripmind"],
        "timezone": "browser",
        "schemaVersion": 39,
        "version": 1,
        "refresh": "10s",
        "time": {"from": "now-1h", "to": "now"},
        "panels": panels,
    }


if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(build(), indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {OUT}")
